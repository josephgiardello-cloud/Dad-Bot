"""Execution Receipts — signed proof of stage completion.

Each successfully completed, non-skipped graph stage generates an
``ExecutionReceipt`` when a stable key is configured. The HMAC-SHA256-signed
record binds:
  - the turn ID
  - the stage name
  - a deterministic ``stage_call_id``
  - the checkpoint hash after the stage
  - a monotonic sequence counter

Receipts are chained: each receipt includes the signature of the previous one.
This creates a tamper-evident continuity chain for the completed graph run.

``ReceiptChain.verify_continuity()`` confirms:
  1. Every receipt signature is valid.
  2. The chain is unbroken (no gaps in sequence numbers).
  3. Expected stages are present in order.
  4. Every receipt belongs to the expected turn.

Receipts are evidence that a particular stage completed and was linked to a
checkpoint hash. They do not prove that the checkpoint is a valid goal
postcondition, and they do not authorize resuming a partial turn.

Architecture role
-----------------
Receipts are generated by TurnGraph after each successful stage and its
after-checkpoint. The bounded chain is stored in ``TurnContext.state`` and is
copied into canonical ``JOB_COMPLETED`` metadata for agent-loop turns only
after continuity verification. The graph's process-random default signer is
not considered stable and does not produce durable evidence. Receipts do not
prove goal postconditions or authorize partial-turn resume.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import time
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

# ---------------------------------------------------------------------------
# Receipt
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ExecutionReceipt:
    """Signed proof that a pipeline stage completed successfully.

    Attributes
    ----------
    turn_id:
        The ``trace_id`` of the turn this receipt belongs to.
    stage:
        Name of the pipeline stage (e.g. ``"temporal"``, ``"inference"``).
    sequence:
        Monotonically increasing counter within the graph run.
    stage_call_id:
        Deterministic idempotency key ``sha256(turn_id:stage:index)[:32]``.
    checkpoint_hash:
        The ``TurnContext.last_checkpoint_hash`` after the stage completed.
    prev_receipt_sig:
        Signature of the immediately preceding receipt in the chain (empty
        string for the very first receipt).
    completed_at:
        Wall-clock epoch when the stage completed (advisory; not used in sig).
    signature:
        HMAC-SHA256 of the canonical payload (see ``_signing_payload``).

    """

    turn_id: str
    stage: str
    sequence: int
    stage_call_id: str
    checkpoint_hash: str
    prev_receipt_sig: str
    completed_at: float
    signature: str = ""

    def _signing_payload(self) -> bytes:
        """Deterministic bytes over which the HMAC is computed."""
        payload = json.dumps(
            {
                "turn_id": self.turn_id,
                "stage": self.stage,
                "sequence": self.sequence,
                "stage_call_id": self.stage_call_id,
                "checkpoint_hash": self.checkpoint_hash,
                "prev_receipt_sig": self.prev_receipt_sig,
            },
            sort_keys=True,
        )
        return payload.encode("utf-8")

    def is_valid(self, key: bytes) -> bool:
        """Return True if *signature* is correct for *key*."""
        if not self.signature:
            return False
        expected = hmac.new(key, self._signing_payload(), "sha256").hexdigest()
        return hmac.compare_digest(expected, self.signature)

    def to_dict(self) -> dict[str, Any]:
        return {
            "turn_id": self.turn_id,
            "stage": self.stage,
            "sequence": self.sequence,
            "stage_call_id": self.stage_call_id,
            "checkpoint_hash": self.checkpoint_hash,
            "prev_receipt_sig": self.prev_receipt_sig,
            "completed_at": self.completed_at,
            "signature": self.signature,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> ExecutionReceipt:
        return cls(
            turn_id=str(d.get("turn_id") or ""),
            stage=str(d.get("stage") or ""),
            sequence=int(d.get("sequence") or 0),
            stage_call_id=str(d.get("stage_call_id") or ""),
            checkpoint_hash=str(d.get("checkpoint_hash") or ""),
            prev_receipt_sig=str(d.get("prev_receipt_sig") or ""),
            completed_at=float(d.get("completed_at") or 0.0),
            signature=str(d.get("signature") or ""),
        )


# ---------------------------------------------------------------------------
# Receipt signer
# ---------------------------------------------------------------------------


class ReceiptSigner:
    """Issues and verifies ExecutionReceipt signatures.

    A random 32-byte key is generated per process by default and is not stable.
    Durable receipt evidence requires at least 32 bytes of explicitly configured
    key material via ``secret_key`` or ``DADBOT_RECEIPT_KEY``.
    """

    _ENV_VAR = "DADBOT_RECEIPT_KEY"

    def __init__(self, secret_key: bytes | None = None) -> None:
        env_key = os.environ.get(self._ENV_VAR, "")
        if secret_key:
            self._key = secret_key
            self._is_stable = len(secret_key) >= 32
        elif env_key:
            encoded_key = env_key.encode("utf-8")
            self._key = encoded_key[:64].ljust(32, b"\x00")
            self._is_stable = len(encoded_key) >= 32
        else:
            self._key = os.urandom(32)
            self._is_stable = False

    @property
    def is_stable(self) -> bool:
        """Whether this signer uses explicitly configured, sufficiently strong key material."""
        return self._is_stable

    @property
    def key_id(self) -> str:
        """Non-secret identifier for matching receipts to their signing key."""
        return hashlib.sha256(self._key).hexdigest()[:16]

    def sign(
        self,
        *,
        turn_id: str,
        stage: str,
        sequence: int,
        stage_call_id: str,
        checkpoint_hash: str,
        prev_receipt_sig: str,
        completed_at: float | None = None,
    ) -> ExecutionReceipt:
        """Create and sign a new ExecutionReceipt."""
        unsigned = ExecutionReceipt(
            turn_id=turn_id,
            stage=stage,
            sequence=sequence,
            stage_call_id=stage_call_id,
            checkpoint_hash=checkpoint_hash,
            prev_receipt_sig=prev_receipt_sig,
            completed_at=completed_at or time.time(),
            signature="",
        )
        sig = hmac.new(self._key, unsigned._signing_payload(), "sha256").hexdigest()
        return ExecutionReceipt(
            turn_id=unsigned.turn_id,
            stage=unsigned.stage,
            sequence=unsigned.sequence,
            stage_call_id=unsigned.stage_call_id,
            checkpoint_hash=unsigned.checkpoint_hash,
            prev_receipt_sig=unsigned.prev_receipt_sig,
            completed_at=unsigned.completed_at,
            signature=sig,
        )

    def verify(self, receipt: ExecutionReceipt) -> bool:
        """Return True if *receipt* has a valid signature for this signer's key."""
        return receipt.is_valid(self._key)


